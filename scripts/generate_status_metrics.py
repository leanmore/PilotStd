#!/usr/bin/env python3
"""
G-032 文档生成器：STATUS.md **全量**自动生成（2026-10-24 起不再保留人工区）。

背景：旧实现只刷新 AUTO-METRICS 区块，人工区长期堆积过期数字（同一文件里
5427 / 2366 / 771 三个测试数、72% / 48% 两个覆盖率并存），成为"文档骗人"的典型。
现改为每次运行重写整份文件：数字只有一个来源，定性状态交给 ROADMAP 与 records。

数据源：
  - coverage.xml → 行覆盖率 / 分支覆盖率
  - pytest --collect-only → 测试用例数
  - VERSION → 版本号；git HEAD → 提交
"""
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

# 控制台-8编码兼容
if sys.platform == "win32" and hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]

PROJECT_ROOT = Path(__file__).resolve().parent.parent
STATUS_FILE = PROJECT_ROOT / "STATUS.md"
BACKUP_FILE = PROJECT_ROOT / "STATUS.md.bak"
COVERAGE_XML = PROJECT_ROOT / "coverage.xml"
VERSION_FILE = PROJECT_ROOT / "VERSION"

AUTO_HEADER = (
    f"<!-- AUTO-GENERATED by scripts/generate_status_metrics.py at "
    f"{datetime.now(timezone.utc).isoformat()} -->"
)
DO_NOT_EDIT = "<!-- DO NOT EDIT MANUALLY. Changes will be overwritten. -->"
FULL_MARKER = "全文由 scripts/generate_status_metrics.py 生成"


def _run_pytest_collect() -> int:
    """运行 pytest --collect-only -q 获取测试总数。"""
    try:
        result = subprocess.run(
            [sys.executable, "-m", "pytest", "tests/", "--collect-only", "-q",
             "--ignore=tests/gui/",
             "--ignore=tests/test_regression_architecture.py",
             "--ignore-glob=*test_ui*.py"],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            cwd=str(PROJECT_ROOT), timeout=300,
        )
        output = (result.stdout or "") + "\n" + (result.stderr or "")
        for line in output.splitlines():
            m = re.search(r"(\d+)\s+tests?\s+(?:selected|collected)", line)
            if m:
                return int(m.group(1))
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError) as e:
        print(f"   ⚠️  pytest collect 失败: {e}")
    return 0


def parse_coverage() -> dict:
    """从 coverage.xml 提取覆盖率数据。返回 {line_cov, branch_cov}，缺失时为 None（不谎报 0）。"""
    result: dict[str, float | None] = {"line_cov": None, "branch_cov": None}
    if not COVERAGE_XML.exists():
        print(f"   ⚠️  {COVERAGE_XML} 不存在，覆盖率记为 n/a")
        return result
    try:
        root = ET.parse(str(COVERAGE_XML)).getroot()
        result["line_cov"] = round(float(root.attrib.get("line-rate", 0)) * 100, 1)
        result["branch_cov"] = round(float(root.attrib.get("branch-rate", 0)) * 100, 1)
    except (ET.ParseError, FileNotFoundError, ValueError) as e:
        print(f"   ⚠️  coverage.xml 解析失败: {e}")
    return result


def _read_version() -> str:
    """读取 VERSION 文件；缺失时返回 unknown。"""
    return VERSION_FILE.read_text(encoding="utf-8").strip() if VERSION_FILE.exists() else "unknown"


def _git_head() -> str:
    """取当前 HEAD 的短 sha 与标题。"""
    try:
        out = subprocess.run(["git", "log", "-1", "--pretty=%h %s"], cwd=str(PROJECT_ROOT),
                             capture_output=True, text=True, encoding="utf-8",
                             errors="replace", timeout=10)
        return (out.stdout or "").strip() or "unknown"
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        return "unknown"


def build_document(tests: int, cov: dict) -> str:
    """生成完整 STATUS.md。

    注意：正文不得出现"覆盖率/测试数/通过率"等词+数字（G-032 维度 4 只放行
    AUTO-METRICS 区块内的数字），故定性内容只给链接，不给数值。
    """
    head = _git_head()
    version = _read_version()
    generated = datetime.now(timezone.utc).isoformat()
    line_cov = "n/a（未生成 coverage.xml）" if cov["line_cov"] is None else f"**{cov['line_cov']}%**"
    branch_cov = "n/a" if cov["branch_cov"] is None else f"{cov['branch_cov']}%"
    return f"""{AUTO_HEADER}
{DO_NOT_EDIT}

# PilotStd 项目状态

> 全文由 scripts/generate_status_metrics.py 生成，**没有人工维护的段落**。
> 定性状态（在做什么、下一步排期）看 `docs/ROADMAP.md`；最近操作记录看 `docs/records/`；
> 功能实现与缺口看 `docs/reference/implementation-digest.md`。

<!-- BEGIN AUTO-METRICS -->

| 指标 | 数值 |
|------|------|
| 版本 | {version} |
| HEAD | {head} |
| 后端用例（非 GUI） | {tests} |
| 后端行覆盖率（排除 UI） | {line_cov} |
| 分支覆盖率 | {branch_cov} |
| 数据采集时间 | {generated} |

<!-- END AUTO-METRICS -->

## 说明

- 本文件为本地状态快照，**不入库**（`STATUS.md` 在 `.gitignore` 内）。
- 任何需要人工判断的状态，一律写进 `docs/ROADMAP.md` 或 `docs/records/`，不写在这里。
"""


def main() -> int:
    """重建整份状态文件：先取数，再整体覆盖写入（旧版含人工区时先备份）。"""
    print("📊 generate_status_metrics.py 开始执行...")
    tests = _run_pytest_collect()
    cov = parse_coverage()
    print(f"   测试数={tests}, 行覆盖={cov['line_cov']}%, 分支覆盖={cov['branch_cov']}%")

    if STATUS_FILE.exists():
        old = STATUS_FILE.read_text(encoding="utf-8")
        if FULL_MARKER not in old:
            shutil.copy2(str(STATUS_FILE), str(BACKUP_FILE))
            print("   🆕 旧版（含人工区）已备份 → STATUS.md.bak")

    STATUS_FILE.write_text(build_document(tests, cov), encoding="utf-8")
    print("   ✅ STATUS.md 已全量重写")
    return 0


if __name__ == "__main__":
    sys.exit(main())
